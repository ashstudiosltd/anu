import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import vm from "node:vm";
import ts from "typescript";
const source = await readFile(new URL("../lib/anu/chat-history.ts", import.meta.url), "utf8");
const exported = {};
vm.runInNewContext(ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText, { exports: exported, TextEncoder });
const { compactMessages, expandMessages, HISTORY_MAX_BYTES } = exported;
const conversation = Array.from({ length: 100 }, (_, index) => ({ role: index % 2 ? "assistant" : "user", text: `${index} — नमस्ते 🙂 ${"content ".repeat(180)}` }));
const packed = compactMessages(conversation);
assert.ok(packed.length <= 60);
assert.ok(Buffer.byteLength(JSON.stringify(packed)) <= HISTORY_MAX_BYTES);
assert.equal(packed[0][0], 0);
assert.equal(packed.at(-1)[1], conversation.at(-1).text);
assert.equal(expandMessages(packed).at(-1).role, "assistant");
assert.equal(JSON.stringify(expandMessages(compactMessages(conversation.slice(-2)))), JSON.stringify(conversation.slice(-2)));
assert.equal(compactMessages([]).length, 0);
assert.throws(() => compactMessages([{ role: "user", text: "🙂".repeat(10000) }]), /too large/);
console.log("PASS: UTF-8 storage budget, recent-message retention, complete-turn boundary, role roundtrip, empty history, and oversized-message rejection.");
